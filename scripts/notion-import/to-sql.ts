/**
 * Turns .notion-export/data/*.json (from export.ts) into .notion-export/import.sql
 * for D1, with cleanup.ts's fixes made first, and reports links to rows that weren't
 * exported.
 *
 *   npm run notion:sql                           # every reference table exported
 *   npm run notion:sql -- campaigns sessions     # just these
 *   npm run notion:apply:local     # then check the app
 *   npm run notion:apply:remote    # production
 *
 * Re-importing replaces every row of the tables it covers, so the game data the
 * app edits in D1 (`owned` in tables.ts) is only written when named. D1 caps a
 * statement at 100 KB, so long pages are written in pieces.
 */
import fs from 'node:fs';
import path from 'node:path';
import { clean } from './cleanup';
import { EXPORT_DIR, TABLES } from './tables';

type Json = any; // eslint-disable-line @typescript-eslint/no-explicit-any

/** Characters per statement: under 100 KB even at three UTF-8 bytes per character. */
const CHUNK = 30_000;

const sql = (value: string | number | null) => (value === null ? 'NULL' : typeof value === 'number' ? String(value) : `'${value.replace(/'/g, "''")}'`);
const seconds = (iso: string) => Math.floor(Date.parse(iso) / 1000);

/** Splits text into pieces of at most CHUNK characters without cutting a surrogate pair. */
function pieces(text: string): string[] {
  const out: string[] = [];
  for (let i = 0; i < text.length; ) {
    let end = Math.min(i + CHUNK, text.length);
    const code = text.charCodeAt(end - 1);
    if (end < text.length && code >= 0xd800 && code <= 0xdbff) end--;
    out.push(text.slice(i, end));
    i = end;
  }
  return out.length ? out : [''];
}

function titleOf(page: Json): string {
  const prop = Object.values<Json>(page.properties).find((p) => p.type === 'title');
  return (prop?.title ?? []).map((t: Json) => t.plain_text).join('');
}

function main() {
  const dataDir = path.join(EXPORT_DIR, 'data');
  const only = process.argv.slice(2).filter((a) => !a.startsWith('--'));
  const unknown = only.filter((k) => !TABLES.some((t) => t.key === k));
  if (unknown.length) throw new Error(`Unknown table(s): ${unknown.join(', ')}`);

  const lines: string[] = ['-- Generated by scripts/notion-import/to-sql.ts. Replaces the rows of every table below.'];
  const exported = TABLES.filter((t) => fs.existsSync(path.join(dataDir, `${t.key}.json`)));
  const chosen = only.length ? TABLES.filter((t) => only.includes(t.key)) : TABLES.filter((t) => !t.owned);
  const missing = chosen.filter((t) => !exported.includes(t)).map((t) => t.key);
  const skipped = only.length ? [] : TABLES.filter((t) => t.owned).map((t) => t.key);
  const read = (key: string) => JSON.parse(fs.readFileSync(path.join(dataDir, `${key}.json`), 'utf8'));
  const all = exported.map((t) => ({ ...read(t.key), owned: t.owned === true }));
  clean(all);
  const tables = all.filter((t) => chosen.some((c) => c.key === t.key));

  // Links are checked against everything exported, written now or not.
  const ids = new Set<string>(all.flatMap((t) => t.rows.map((r: Json) => r.page.id)));
  const tableByDatabase = new Map<string, string>(all.map((t) => [t.notionDatabaseId, t.key]));
  const dangling = new Map<string, Set<string>>();

  for (const t of tables) {
    lines.push(
      `INSERT INTO content_tables (key, notion_database_id, name, schema, owned, imported_at) VALUES (${sql(t.key)}, ${sql(t.notionDatabaseId)}, ${sql(t.name)}, ${sql(JSON.stringify(t.schema))}, ${t.owned ? 1 : 0}, unixepoch())` +
        ' ON CONFLICT (key) DO UPDATE SET notion_database_id = excluded.notion_database_id, name = excluded.name, schema = excluded.schema, owned = excluded.owned, imported_at = excluded.imported_at;',
      `DELETE FROM content_rows WHERE table_key = ${sql(t.key)};`
    );
    for (const { page, body } of t.rows) {
      const pageJson = JSON.stringify(page);
      const bodyJson = JSON.stringify(body);
      const whole = pageJson.length + bodyJson.length <= CHUNK;
      lines.push(
        `INSERT INTO content_rows (id, table_key, title, page, body, created_at, updated_at) VALUES (${sql(page.id)}, ${sql(t.key)}, ${sql(titleOf(page))}, ` +
          `${sql(whole ? pageJson : '')}, ${sql(whole ? bodyJson : '')}, ${seconds(page.created_time)}, ${seconds(page.last_edited_time)});`
      );
      if (!whole) {
        for (const p of pieces(pageJson)) lines.push(`UPDATE content_rows SET page = page || ${sql(p)} WHERE id = ${sql(page.id)};`);
        for (const p of pieces(bodyJson)) lines.push(`UPDATE content_rows SET body = body || ${sql(p)} WHERE id = ${sql(page.id)};`);
      }

      for (const [name, prop] of Object.entries<Json>(page.properties)) {
        if (prop.type !== 'relation') continue;
        const target = t.schema[name]?.relation?.database_id;
        for (const { id } of prop.relation) {
          if (ids.has(id)) continue;
          const label = `${t.key}.${name} → ${tableByDatabase.get(target) ?? `Notion database ${target ?? '?'}`}`;
          if (!dangling.has(label)) dangling.set(label, new Set());
          dangling.get(label)!.add(id);
        }
      }
    }
  }

  const file = path.join(EXPORT_DIR, 'import.sql');
  fs.writeFileSync(file, lines.join('\n') + '\n');
  const rowCount = tables.reduce((n, t) => n + t.rows.length, 0);
  console.log(`${file}: ${tables.length} tables, ${rowCount} rows, ${Math.round(fs.statSync(file).size / 1024)} KB`);
  if (missing.length) console.log(`Not exported yet (skipped): ${missing.join(', ')}`);
  if (skipped.length) console.log(`Edited in D1, so left out unless named: ${skipped.join(', ')}`);
  if (dangling.size) {
    console.log('\nLinks to rows that were not imported (kept as Notion page ids):');
    for (const [label, set] of [...dangling].sort()) console.log(`  ${label}: ${set.size} row(s)`);
  }
}

main();
